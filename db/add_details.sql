CREATE TABLE IF NOT EXISTS profession_details (
    profession_id INTEGER PRIMARY KEY REFERENCES professions(id),
    reality TEXT,           -- Реальность профессии (не романтика)
    daily_tasks TEXT,       -- Что делает каждый день
    stress_level TEXT,      -- Высокий / Средний / Низкий
    education_path TEXT,    -- Как учиться
    career_path TEXT,       -- Траектория роста
    pros JSONB,             -- Плюсы ["...", "..."]
    cons JSONB              -- Минусы ["...", "..."]
);

